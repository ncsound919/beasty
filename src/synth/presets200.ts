function toPreset(entry: BankPatch): SynthPreset {
  return {
    id: entry.id,
    name: entry.name,
    category: entry.category,
    tone: entry.tone,
    tags: entry.tags,
    description: entry.description,
    isFactory: true,
    // Authored patches store only their differences; the runtime merges them over
    // the panel defaults, exactly like a saved user patch.
    params: { ...base, ...entry.p },
  };
}

// ---------------------------------------------------------------------------
// Factory expansion: the authored patches above are the curated core. Each one
// gains deterministic siblings that stay inside the parameter specs, so the
// browser ships exactly 200 factory patches with no duplicates.
// ---------------------------------------------------------------------------
const ROMAN = ['II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII'];

function hash(seed: number): number {
  const x = Math.sin(seed * 12.9898 + 4.1414) * 43758.5453;
  return x - Math.floor(x);
}

function variantOf(src: SynthPreset, n: number): SynthPreset {
  const params: ParamState = { ...src.params };
  const tweak = (id: ParamID, amount: number, k: number) => {
    const spec = PARAM_SPECS[id];
    if (!spec || spec.choices) return;
    const r = hash(n * 17 + k * 3 + id.length);
    let v = params[id] + (r * 2 - 1) * (spec.max - spec.min) * amount;
    v = Math.max(spec.min, Math.min(spec.max, v));
    if (spec.step >= 1) v = Math.round(v);
    params[id] = v;
  };

  tweak('FILTER_CUTOFF', 0.16, 1);
  tweak('FILTER_RES', 0.14, 2);
  tweak('FILTER_ENV', 0.12, 3);
  tweak('FENV_DECAY', 0.16, 4);
  tweak('FENV_SUSTAIN', 0.14, 5);
  tweak('AENV_DECAY', 0.14, 6);
  tweak('AENV_RELEASE', 0.16, 7);
  tweak('MIX_OSC2', 0.12, 8);
  tweak('MIX_OSC3', 0.12, 9);
  tweak('ANALOG_DRIFT', 0.20, 10);
  tweak('LFO1_RATE', 0.20, 11);
  tweak('FX_REVERB_MIX', 0.14, 12);
  tweak('FX_DELAY_MIX', 0.14, 13);
  tweak('FX_PHASER_DEPTH', 0.16, 14);

  return {
    ...src,
    id: `${src.id}-${n}`,
    name: `${src.name} ${ROMAN[n - 1] ?? n}`,
    tags: src.tags ? [...src.tags] : [],
    isFactory: true,
    params,
  };
}

const AUTHORED_FACTORY: SynthPreset[] = [...QUICK_START_PRESETS, ...BANK.map(toPreset)];

function expandFactory(list: SynthPreset[], target: number): SynthPreset[] {
  const out = list.slice();
  let i = 0;
  while (out.length < target) {
    const base = list[i % list.length];
    const variant = Math.floor(i / list.length) + 1;
    out.push(variantOf(base, variant));
    i += 1;
  }
  return out.slice(0, target);
}

export const FACTORY_PRESETS: SynthPreset[] = expandFactory(AUTHORED_FACTORY, 200);
